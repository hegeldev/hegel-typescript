// Bumps the pinned libhegel release (src/libhegel-version.ts).
//
// Queries a hegel-rust GitHub release (the latest by default, or the one named
// by the version argument), checks that it publishes an artifact for every
// supported platform, and writes a fresh, generated source file pinning its
// version. Run it to bump the pinned release, then commit the result.
//
// Usage:
//   node scripts/update-libhegel.mjs [<version>]

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { PLATFORMS } from "./fetch-libhegel.mjs";

const REPO = "hegeldev/hegel-rust";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = path.join(ROOT, "src", "libhegel-version.ts");

/**
 * Query a hegel-rust release and return its version (tag without a leading
 * "v"), verifying that every supported platform's artifact is published.
 */
function releaseVersion(want) {
  const args = ["release", "view"];
  if (want) {
    args.push(`v${want.replace(/^v/, "")}`);
  }
  args.push("--repo", REPO, "--json", "tagName,assets");

  const rel = JSON.parse(execFileSync("gh", args, { encoding: "utf8" }));
  const published = new Set(rel.assets.map((asset) => asset.name));
  const missing = PLATFORMS.map((p) => p.asset).filter((asset) => !published.has(asset));
  if (missing.length > 0) {
    throw new Error(`release ${rel.tagName} is missing assets: ${missing.join(", ")}`);
  }

  const version = rel.tagName.replace(/^v/, "");
  if (want && version !== want.replace(/^v/, "")) {
    throw new Error(`requested release v${want.replace(/^v/, "")} but got tag ${rel.tagName}`);
  }
  return version;
}

function render(version) {
  return `// Code generated by scripts/update-libhegel.mjs; DO NOT EDIT.
//
// Run \`just update-libhegel\` to pin the latest hegel-rust release.

/**
 * The pinned libhegel version this client targets.
 */
export const LIBHEGEL_VERSION = ${JSON.stringify(version)};
`;
}

function main() {
  const version = releaseVersion(process.argv[2] ?? "");
  writeFileSync(OUTPUT, render(version));
  process.stderr.write(`pinned libhegel v${version} in ${path.relative(ROOT, OUTPUT)}\n`);
}

main();
