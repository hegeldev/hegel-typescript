// Bumps the pinned libhegel release.
//
// Queries a libhegel GitHub release in hegel-rust (the latest by default, or
// the one named by the argument), checks that it publishes an artifact for
// every supported platform plus the Wasm module and its checksum sidecar, and
// regenerates the three generated pin files for that release:
//
//   src/libhegel-version.ts   the native pin (LIBHEGEL_VERSION)
//   src/browser/artifact.json the Wasm pin: release tag, its commit, the
//                             published asset's SHA-256
//   src/browser/artifact.ts   the browser entry's copy of the Wasm pin (it
//                             cannot import JSON portably)
//
// Run it to bump the pinned release, then `npm run prepare:wasm -- release`
// to download and verify the pinned Wasm, and commit the result.
//
// hegel-rust tags every release `v<hegeltest version>` with no GitHub release
// attached; a release that includes hegel-c additionally tags
// `libhegel-v<hegel-c version>`, and that tag carries the GitHub release and
// the libhegel binaries. Only the `libhegel-v` releases exist to be pinned.
//
// Usage:
//   node scripts/update-libhegel.mjs [<version> | libhegel-v<version>]

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { PLATFORMS, releaseTag } from "./fetch-libhegel.mjs";
import { PIN, tagCommit } from "./wasm-artifact.mjs";

const REPO = "hegeldev/hegel-rust";
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const VERSION_TS = path.join(ROOT, "src", "libhegel-version.ts");
const PIN_JSON = path.join(ROOT, "src", "browser", "artifact.json");
const PIN_TS = path.join(ROOT, "src", "browser", "artifact.ts");

/**
 * The libhegel version named by a `libhegel-v<version>` tag, or null for any
 * other tag (a hegeltest-only `v<version>` release, say).
 */
function versionOfTag(tag) {
  const match = /^libhegel-v(.+)$/.exec(tag);
  return match ? match[1] : null;
}

/** Normalize a requested `<version>` / `v<version>` / `libhegel-v<version>`. */
function requestedVersion(want) {
  return want.replace(/^(libhegel-)?v/, "");
}

/**
 * Query a libhegel release and return its version (tag without the leading
 * "libhegel-v") and tag, verifying that every supported platform's artifact
 * and the Wasm module (with its checksum sidecar) are published.
 */
function release(want) {
  const args = ["release", "view"];
  if (want) {
    args.push(releaseTag(requestedVersion(want)));
  }
  args.push("--repo", REPO, "--json", "tagName,assets");

  const rel = JSON.parse(execFileSync("gh", args, { encoding: "utf8" }));
  const version = versionOfTag(rel.tagName);
  if (version === null) {
    throw new Error(
      `release ${rel.tagName} is not a libhegel release (expected a libhegel-v* tag)`,
    );
  }

  const published = new Set(rel.assets.map((asset) => asset.name));
  const required = [...PLATFORMS.map((p) => p.asset), PIN.asset, `${PIN.asset}.sha256`];
  const missing = required.filter((asset) => !published.has(asset));
  if (missing.length > 0) {
    throw new Error(`release ${rel.tagName} is missing assets: ${missing.join(", ")}`);
  }

  if (want && version !== requestedVersion(want)) {
    throw new Error(
      `requested release ${releaseTag(requestedVersion(want))} but got tag ${rel.tagName}`,
    );
  }
  return { version, tag: rel.tagName };
}

/** The SHA-256 the release publishes for the Wasm asset, from its sidecar. */
async function publishedChecksum(tag) {
  const url = `https://github.com/${REPO}/releases/download/${tag}/${PIN.asset}.sha256`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`HTTP ${response.status} downloading ${url}`);
  const match = /^([a-f0-9]{64})(?:\s|$)/.exec((await response.text()).trim());
  if (!match) throw new Error(`Malformed checksum sidecar for ${PIN.asset} in ${tag}`);
  return match[1];
}

function renderVersion(version) {
  return `// Code generated by scripts/update-libhegel.mjs; DO NOT EDIT.
//
// Run \`just update-libhegel\` to pin the latest libhegel release.

/**
 * The pinned libhegel version this client targets.
 */
export const LIBHEGEL_VERSION = ${JSON.stringify(version)};
`;
}

function renderArtifact(pin) {
  return `// Code generated by scripts/update-libhegel.mjs; DO NOT EDIT.
//
// The browser entry's copy of src/browser/artifact.json (it cannot import JSON
// portably). Run \`just update-libhegel\` to regenerate both.
import { LIBHEGEL_VERSION } from "../libhegel-version.js";

/** Exact raw Wasm build identity; development pins cannot authorize publication. */
export const WASM_ARTIFACT = {
  version: LIBHEGEL_VERSION,
  asset: ${JSON.stringify(pin.asset)},
  sha256: ${JSON.stringify(pin.sha256)},
} as const;
`;
}

async function main() {
  const { version, tag } = release(process.argv[2] ?? "");
  const pin = {
    version,
    source: tagCommit(tag),
    sha256: await publishedChecksum(tag),
    target: PIN.target,
    asset: PIN.asset,
    published: true,
    release: { tag },
  };
  writeFileSync(VERSION_TS, renderVersion(version));
  writeFileSync(PIN_JSON, JSON.stringify(pin, null, 2) + "\n");
  writeFileSync(PIN_TS, renderArtifact(pin));
  const files = [VERSION_TS, PIN_JSON, PIN_TS].map((f) => path.relative(ROOT, f)).join(", ");
  process.stderr.write(
    `pinned libhegel ${version} (${tag}) in ${files}\n` +
      "run `npm run prepare:wasm -- release` to download and verify the pinned Wasm\n",
  );
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
